"""
survey_spots.py — record the home pose and waypoint from the live robot.

    python3 survey_spots.py                 # home + 4 waypoint
    python3 survey_spots.py --spots 3       # home + 3 waypoint

Drive Acrux (teleop) to each marked spot, facing the waypoint direction, press Enter, and the
current /amcl_pose is recorded. The result is written to a NEW file
(waypoints_surveyed.yaml by default) so the commented template waypoints.yaml is never
clobbered. Run the mission with it:

    python3 mission_node.py --count 3 --waypoints waypoints_surveyed.yaml

Needs ROS 2 only for the recording itself; the maths and the file writer are
plain Python and unit-tested (tests/test_survey.py).
"""

import argparse
import math
import os
import sys

import yaml

import waypoint_config
from mission import Pose

DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "waypoints_surveyed.yaml")
AMCL_TOPIC = "/amcl_pose"
MIN_SPACING_M = 1.2        # closer than this and the 0.55 m inflation halos overlap
MAX_POS_STD_M = 0.30       # heuristic: AMCL position std-dev above this = not converged
MAX_YAW_STD_RAD = 0.20


# ---------------------------------------------------------------- pure helpers

def quaternion_to_yaw(x, y, z, w):
    """Yaw (rotation about Z, radians, -pi..pi) of a quaternion."""
    return math.atan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z))


def pose_quality_warning(covariance):
    """Warning text if AMCL's 6x6 row-major covariance says it is not converged.

    Indices: 0 = var(x), 7 = var(y), 35 = var(yaw). Returns None when fine.
    The thresholds are rules of thumb, not guarantees.
    """
    if len(covariance) != 36:
        return "pose has no usable covariance - cannot judge localization quality"
    pos_std = math.sqrt(max(covariance[0], covariance[7], 0.0))
    yaw_std = math.sqrt(max(covariance[35], 0.0))
    problems = []
    if pos_std > MAX_POS_STD_M:
        problems.append(f"position uncertainty {pos_std:.2f} m")
    if yaw_std > MAX_YAW_STD_RAD:
        problems.append(f"heading uncertainty {yaw_std:.2f} rad")
    if problems:
        return ("AMCL is not confident (" + ", ".join(problems) + "). Check that the scan "
                "lines up with the map in RViz and set the initial pose before surveying.")
    return None


def spacing_warnings(poses, min_distance=MIN_SPACING_M):
    """One message per pair of poses (incl. home) closer than `min_distance`."""
    out = []
    for i, a in enumerate(poses):
        for b in poses[i + 1:]:
            d = math.hypot(a.x - b.x, a.y - b.y)
            if d < min_distance:
                out.append(f"'{a.label}' and '{b.label}' are only {d:.2f} m apart "
                           f"(want >= {min_distance:.1f} m between spots)")
    return out


def _pose_dict(pose):
    return {"label": pose.label, "x": round(pose.x, 3), "y": round(pose.y, 3),
            "yaw": round(pose.yaw, 3)}


def render_waypoints_yaml(home, waypoints, base=None):
    """Return waypoints.yaml text for a surveyed run.

    `base` is an existing WaypointConfig whose frame_id / retry / timeout settings
    are carried over; defaults are used when it is None.
    """
    data = {
        "surveyed": True,
        "frame_id": base.frame_id if base else "map",
        "max_auto_retries": base.max_auto_retries if base else 1,
        "goal_timeout_s": base.goal_timeout_s if base else 120,
        "home": _pose_dict(home),
        "waypoints": [_pose_dict(s) for s in waypoints],
    }
    header = ("# Generated by survey_spots.py - real map coordinates (metres, radians).\n"
              "# Valid only for the map they were surveyed on: re-survey if the map is rebuilt.\n")
    return header + yaml.safe_dump(data, sort_keys=False, default_flow_style=False)


def write_surveyed(path, home, waypoints, base=None):
    """Write the file, then reload it through the real validator."""
    text = render_waypoints_yaml(home, waypoints, base)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return waypoint_config.load_config(path)   # raises if what we wrote is invalid


# ------------------------------------------------------------------ ROS part

def _record(node, label):
    """Block until the user presses Enter, then return the latest AMCL Pose."""
    import rclpy
    while True:
        answer = input(f"\n[{label}] drive Acrux onto the spot, facing the waypoint direction, "
                       "then press Enter to record (s = skip, q = quit): ").strip().lower()
        if answer == "q":
            raise KeyboardInterrupt
        if answer == "s":
            return None
        node.latest = None
        deadline = node.get_clock().now().nanoseconds + 3_000_000_000
        while node.latest is None and node.get_clock().now().nanoseconds < deadline:
            rclpy.spin_once(node, timeout_sec=0.1)
        msg = node.latest
        if msg is None:
            print(f"  no message on {AMCL_TOPIC} within 3 s - is AMCL running and the "
                  "initial pose set? (same ROS_DOMAIN_ID?)")
            continue
        if msg.header.frame_id != "map":
            print(f"  pose is in frame '{msg.header.frame_id}', expected 'map' - not recording.")
            continue
        o = msg.pose.pose.orientation
        pose = Pose(x=msg.pose.pose.position.x, y=msg.pose.pose.position.y,
                    yaw=quaternion_to_yaw(o.x, o.y, o.z, o.w), label=label)
        print(f"  x={pose.x:.3f}  y={pose.y:.3f}  yaw={pose.yaw:.3f} rad "
              f"({math.degrees(pose.yaw):.0f} deg)")
        warning = pose_quality_warning(list(msg.pose.covariance))
        if warning:
            print(f"  WARNING: {warning}")
        if input("  keep this pose? [Y/n] ").strip().lower() in ("", "y", "yes"):
            return pose


def main(argv=None):
    parser = argparse.ArgumentParser(description="Survey Acrux home + waypoint from /amcl_pose")
    parser.add_argument("--spots", type=int, default=waypoint_config.MAX_WAYPOINTS,
                        help=f"number of waypoint (1-{waypoint_config.MAX_WAYPOINTS}, default "
                             f"{waypoint_config.MAX_WAYPOINTS})")
    parser.add_argument("--out", default=DEFAULT_OUT, help="file to write")
    parser.add_argument("--base", default=waypoint_config.DEFAULT_CONFIG_FILE,
                        help="existing waypoints.yaml to copy retry/timeout settings from")
    parser.add_argument("--sim", action="store_true", help="use_sim_time=true (Gazebo)")
    args = parser.parse_args(argv)
    if not 1 <= args.spots <= waypoint_config.MAX_WAYPOINTS:
        parser.error(f"--spots must be 1-{waypoint_config.MAX_WAYPOINTS}")

    try:
        base = waypoint_config.load_config(args.base)
    except (OSError, ValueError):
        base = None

    import rclpy
    from geometry_msgs.msg import PoseWithCovarianceStamped
    from rclpy.node import Node
    from rclpy.parameter import Parameter

    rclpy.init()
    node = Node("waypoint_survey")
    if args.sim:
        node.set_parameters([Parameter("use_sim_time", Parameter.Type.BOOL, True)])
    node.latest = None

    def _on_pose(msg):
        node.latest = msg
    node.create_subscription(PoseWithCovarianceStamped, AMCL_TOPIC, _on_pose, 10)

    labels = ["Home"] + [f"Waypoint {i + 1}" for i in range(args.spots)]
    recorded = []
    try:
        for label in labels:
            pose = _record(node, label)
            if pose is None:
                print(f"  skipped {label}")
                if label == "Home":
                    print("Home is required - aborting.")
                    return 1
                break          # waypoints are served in order: no gaps allowed
            recorded.append(pose)
    except KeyboardInterrupt:
        print("\nquit - nothing written.")
        return 1
    finally:
        node.destroy_node()
        rclpy.shutdown()

    home, waypoints = recorded[0], recorded[1:]
    if not waypoints:
        print("No waypoint recorded - nothing written.")
        return 1
    for line in spacing_warnings(recorded):
        print(f"WARNING: {line}")
    config = write_surveyed(args.out, home, waypoints, base)
    print(f"\nWrote {args.out}  ({len(config.waypoints)} waypoint(s) + home, surveyed: true)")
    print(f"Run:  python3 mission_node.py --count {len(config.waypoints)} --waypoints {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
